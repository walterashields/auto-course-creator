#!/usr/bin/env python3
"""
compiler/transcript_loader.py

C47: transcript-driven script ingestion.

For videos whose manifest sets ``transcript_source``, the narration script is
NOT generated by the LLM. It is built verbatim from a marked transcript file
stored under ``compiler/transcripts/``. Beat markers look like::

    [B02 demo — comment block skeleton]
    Now, jumping right into our best practice, ...

The text between markers is FIXED: no additions, no deletions, no paraphrase.
The fidelity invariant: the concatenation of all beat texts must equal the
transcript body (whitespace/punctuation-normalized compare). Coverage is
logged at load as ``wsda-fidelity: coverage=100%``.

Each transcript beat maps onto the existing ``ScriptBeat`` structure
(kind, text, action) so every downstream stage — per-beat TTS, choreography
planning, the seam contract, the park watchdog, rendering, and the gates —
works unchanged. The per-marker action map below is the teaching order and
drives the vision agent.
"""

from __future__ import annotations

import difflib
import re
import sys
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from .narrator import ScriptBeat

# ---------------------------------------------------------------------------
# Transcript model
# ---------------------------------------------------------------------------

BEAT_MARKER_RE = re.compile(r"^\[(B\d{2})\s+([^\]]+)\]\s*$")

# Transcript label word -> ScriptBeat kind. "explore" beats (B04-B06) are a
# C47 capability: exploration is content, not a cutaway.
KIND_MAP = {
    "opening": "opening",
    "demo": "demo",
    "explore": "explore",
    "validation": "validation",
    "takeaway": "concept",
    "close": "close",
}


@dataclass
class TranscriptBeat:
    """One marked beat from a transcript file."""

    marker: str
    label: str
    kind: str
    text: str


def parse_transcript(text: str) -> List[TranscriptBeat]:
    """Parse marked beats out of a transcript body."""
    beats: List[TranscriptBeat] = []
    current_marker: Optional[str] = None
    current_label = ""
    body_lines: List[str] = []

    def _flush() -> None:
        if current_marker is None:
            return
        body = " ".join(line.strip() for line in body_lines).strip()
        label_word = current_label.split()[0].lower() if current_label.strip() else "demo"
        kind = KIND_MAP.get(label_word, "demo")
        beats.append(
            TranscriptBeat(
                marker=current_marker,
                label=current_label,
                kind=kind,
                text=body,
            )
        )

    for line in text.split("\n"):
        match = BEAT_MARKER_RE.match(line.strip())
        if match:
            _flush()
            current_marker = match.group(1)
            current_label = match.group(2).strip()
            body_lines = []
        elif current_marker is not None:
            body_lines.append(line)
    _flush()
    return beats


def normalize_fidelity_text(text: str) -> str:
    """Whitespace/punctuation normalization for the fidelity compare."""
    text = text.replace("\u2014", "-").replace("\u2013", "-")
    text = re.sub(r"\s+", " ", text)
    # Normalize spaced punctuation so typographic variance cannot mask drift.
    text = re.sub(r"\s+([,.;:!?])", r"\1", text)
    return text.strip()


def transcript_body_text(parsed: List[TranscriptBeat]) -> str:
    """The transcript body a parser saw: beat texts joined with a single space."""
    return " ".join(b.text for b in parsed)


def fidelity_coverage(beat_texts: List[str], transcript_text: str) -> float:
    """
    Return the share (0-100) of the transcript covered by the beat texts.

    100.0 means the concatenation of the beat texts equals the transcript body
    under whitespace/punctuation normalization — nothing added, nothing lost.
    """
    beats_norm = normalize_fidelity_text(" ".join(t for t in beat_texts if t.strip()))
    transcript_norm = normalize_fidelity_text(transcript_text)
    if not transcript_norm:
        return 0.0
    if beats_norm == transcript_norm:
        return 100.0
    return round(100.0 * difflib.SequenceMatcher(None, beats_norm, transcript_norm).ratio(), 1)


# ---------------------------------------------------------------------------
