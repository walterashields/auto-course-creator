#
# Teaching order = action order. B07 composes FROM FIRST below the comment
# block; B09 is the insert-above primitive: SELECT is inserted at the line
# above the FROM clause, not appended. The final editor content is the C46
# blank-free canonical block:
#
#   /*
#   Created By: Walter Shields
#   Create Date: <record date>
#   Description: customer first and last names with email addresses
#   */
#   SELECT FirstName,
#     LastName,
#     Email
#   FROM Customer;


def _record_date(record_date: Optional[str] = None) -> str:
    """Return the Create Date line content: month, followed by day, year."""
    if record_date:
        return record_date
    today = date.today()
    return f"{today.strftime('%B')} {today.day}, {today.year}"


